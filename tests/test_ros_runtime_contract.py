from __future__ import annotations

import json
import re
from pathlib import Path


ROOT = Path(__file__).parents[1]
REPORT_PATH = ROOT / "artifacts/phase0/ros-humble-runtime.json"
DOCKERFILE_PATH = ROOT / "docker/ros.Dockerfile"
ENTRYPOINT_PATH = ROOT / "docker/ros-entrypoint.sh"
COMPOSE_PATH = ROOT / "compose.yaml"
DOCKERIGNORE_PATH = ROOT / ".dockerignore"
DDS_TEMPLATE_PATH = ROOT / "config/dds/fastdds-rootless-tcp.xml.in"
DDS_EVIDENCE_PATH = ROOT / "artifacts/phase0/rootless-dds-smoke.json"
DDS_GENERATOR_PATH = ROOT / "tools/generate_dds_profiles.py"
ISAAC_ENV_PATH = ROOT / "tools/isaac-ros-env.sh"

DIGEST = "sha256:c3eb3a8576b8b4fee5988244135855a1a2146df93ee1523878cebdc0fb1be9a6"
REQUIRED_PACKAGES = {
    "python3-colcon-common-extensions",
    "python3-rosdep",
    "python3-vcstool",
    "ros-humble-controller-manager",
    "ros-humble-joint-state-broadcaster",
    "ros-humble-joint-trajectory-controller",
    "ros-humble-moveit",
    "ros-humble-moveit-configs-utils",
    "ros-humble-rmw-fastrtps-cpp",
    "ros-humble-ros2-control",
    "ros-humble-ros2-controllers",
    "ros-humble-xacro",
}


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def test_runtime_report_is_valid_and_scoped() -> None:
    report = json.loads(_read(REPORT_PATH))
    assert report["artifact"] == "ros-humble-runtime"
    assert report["phase"] == "P0.3"
    assert report["architecture"] == "host-isaac-ros-container"


def test_base_image_is_content_addressed() -> None:
    report = json.loads(_read(REPORT_PATH))
    image = report["base_image"]
    assert image["reference"] == f"osrf/ros@{DIGEST}"
    assert image["digest"] == DIGEST
    assert image["verification"] == "local docker image inspect RepoDigests"
    assert re.fullmatch(r"sha256:[0-9a-f]{64}", image["digest"])


def test_dockerfile_uses_pinned_base_and_required_packages() -> None:
    text = _read(DOCKERFILE_PATH)
    assert f"osrf/ros@{DIGEST}" in text
    assert "FROM ${ROS_BASE_IMAGE}" in text
    for package in REQUIRED_PACKAGES:
        assert package in text


def test_report_package_set_matches_dockerfile_contract() -> None:
    report = json.loads(_read(REPORT_PATH))
    assert set(report["required_apt_packages"]) == REQUIRED_PACKAGES


def test_ros_network_contract_is_consistent() -> None:
    report = json.loads(_read(REPORT_PATH))
    ros = report["ros"]
    assert ros == {
        "distro": "humble",
        "rmw_implementation": "rmw_fastrtps_cpp",
        "ros_localhost_only": "0",
        "ros_domain_id_default": "73",
        "network_mode": "rootless_bridge_with_explicit_tcpv4",
    }
    compose = _read(COMPOSE_PATH)
    assert "network_mode: host" not in compose
    assert "driver: bridge" in compose
    assert 'ROS_LOCALHOST_ONLY: "0"' in compose
    assert "RMW_IMPLEMENTATION: rmw_fastrtps_cpp" in compose
    assert "ROS_DOMAIN_ID: ${ROS_DOMAIN_ID:-73}" in compose
    assert "FASTRTPS_DEFAULT_PROFILES_FILE" in compose
    # P1.A: the container profile is client-only, so compose publishes no
    # container port anymore (the host listener owns TCP 17650 alone).
    assert "17651" not in compose
    assert "DDS_CONTAINER_PORT" not in compose
    assert "ports:" not in compose


def test_entrypoint_sources_ros_and_supports_self_check() -> None:
    text = _read(ENTRYPOINT_PATH)
    assert "source /opt/ros/humble/setup.bash" in text
    assert "/workspace/ros_ws/install/setup.bash" in text
    assert '"${1:-}" == "self-check"' in text
    assert 'exec "$@"' in text


def test_no_legacy_planner_or_mode_b_runtime_is_imported() -> None:
    combined = "\n".join(
        _read(path) for path in (DOCKERFILE_PATH, ENTRYPOINT_PATH, COMPOSE_PATH)
    )
    forbidden = ("planner_ws", "planner-entrypoint", "grpc", "mode_b", "50051")
    for token in forbidden:
        assert token not in combined.lower()


def test_build_context_is_minimal() -> None:
    lines = set(_read(DOCKERIGNORE_PATH).splitlines())
    assert lines == {
        "**",
        "!docker/",
        "!docker/ros.Dockerfile",
        "!docker/ros-entrypoint.sh",
    }


def test_workspace_is_mounted_not_baked_into_image() -> None:
    dockerfile = _read(DOCKERFILE_PATH)
    compose = _read(COMPOSE_PATH)
    assert "COPY ros_ws" not in dockerfile
    assert "./ros_ws:/workspace/ros_ws" in compose


def test_fastdds_profile_forces_explicit_tcp_without_shm_or_multicast() -> None:
    template = _read(DDS_TEMPLATE_PATH)
    assert "<type>TCPv4</type>" in template
    assert "<useBuiltinTransports>false</useBuiltinTransports>" in template
    assert "<avoid_builtin_multicast>true</avoid_builtin_multicast>" in template
    assert "<physical_port>__PEER_PORT__</physical_port>" not in template
    assert "<physical_port>" not in template  # generated by the tool, not hardcoded
    assert "UDPv4" not in template
    assert "SHM" not in template
    generator = _read(DDS_GENERATOR_PATH)
    assert "<physical_port>" in generator
    assert "host_address()" in generator
    assert "10.198.61.26" not in generator


