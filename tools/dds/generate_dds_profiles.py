#!/usr/bin/env python3
"""Generate Fast DDS XML profiles for host Isaac Sim <-> ROS Humble container DDS.

The host runs Isaac Sim 5.1 (pip install, internal Fast DDS 2.6.10) as a plain
host process. The ROS container runs Fast DDS 2.6.x under rootless Docker
(slirp4netns). Raw probes on this workstation proved:

- container -> host UDP only reaches the *real host IP* (slirp NAT path);
- host -> container UDP only reaches *published container ports* (RootlessKit
  binds them on the host; traffic enters the container via its bridge gateway).

Default Fast DDS discovery (SHM + multicast + auto participant IDs) cannot
cross that boundary, so the generated profiles force a deterministic setup:

- UDPv4 transport only (``useBuiltinTransports=false``): no shared memory and
  no multicast dependency;
- fixed RTPS participant IDs (host=0, container=1) so all RTPS ports are
  deterministic functions of the ROS domain id;
- explicit ``initialPeersList`` so discovery is unicast-only and deterministic;
- the container additionally announces ``127.0.0.1:<published port>`` locator
  entries next to its wildcard entries so host->container user traffic targets
  the published ports while its sockets keep listening on all interfaces.

Usage:
    python3 tools/dds/generate_dds_profiles.py                       # auto IP
    python3 tools/dds/generate_dds_profiles.py --host-ip 10.0.0.5
    python3 tools/dds/generate_dds_profiles.py --transport tcp       # fallback
    python3 tools/dds/generate_dds_profiles.py --print               # stdout only

The current IP is never hardcoded anywhere: it is auto-detected at generation
time and embedded only in the generated output.
"""

from __future__ import annotations

import argparse
import json
import re
import socket
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUTPUT_DIR = REPO_ROOT / "config" / "dds" / "generated"

# RTPS default port mapping (DDS 2.3 / RTPS 2.5): PB + DG*domain + PG*pid + [d0..d2]
RTPS_PB = 7400
RTPS_DG = 250
RTPS_PG = 100
RTPS_D0 = 0  # multicast metatraffic offset (never used: no multicast)
RTPS_D1 = 10  # unicast metatraffic offset
RTPS_D2 = 1  # unicast user traffic offset

# Fixed participant IDs (deterministic endpoints).
HOST_PARTICIPANT_ID = 0
CONTAINER_PARTICIPANT_ID = 1

# Fast DDS TCPv4 server port used when --transport tcp is selected. The
# container is the TCP server (its listening port is published 1:1) and the
# host is a pure TCP client.
TCP_CONTAINER_PORT = 7660

SCHEMA_VERSION = "rocobrick-dds-profiles/v1"
DOMAIN_COMMENT = "rocobrick: domain_id={domain} transport={transport} host_ip={host_ip}"

