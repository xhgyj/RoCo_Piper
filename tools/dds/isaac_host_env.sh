#!/usr/bin/env bash
# Host-side Isaac Sim <-> ROS container DDS environment helper.
#
# Source this file from the repository root (or any shell):
#   source tools/dds/isaac_host_env.sh
#
# It wires the current shell so Isaac Sim's Python (pip install under
# .venv, bridge runtime under .venv/lib/python3.11/site-packages/isaacsim)
# can import the internal rclpy and talk Fast DDS with the ROS container:
#
#   - ROS_DISTRO/RMW_IMPLEMENTATION/ROS_DOMAIN_ID/ROS_LOCALHOST_ONLY
#   - LD_LIBRARY_PATH += isaacsim.ros2.bridge/humble/lib (Fast DDS 2.6.10)
#   - PYTHONPATH += isaacsim.ros2.bridge/humble/rclpy (internal rclpy)
#   - FASTRTPS_DEFAULT_PROFILES_FILE -> generated host profile
#
# Helpers:
#   isaac_dds_python script.py [args...]   run the Isaac venv Python with env
#   isaac_dds_env_check                    print the effective environment
#
# The host IP is never hardcoded here: profiles are generated by
# tools/dds/generate_dds_profiles.py, which auto-detects it.

# Resolve repository root from this script's location.
_rocobrick_dds_env_root() {
    local script_dir
    script_dir="$(cd "$(dirname "${BASH_SOURCE[0]:-.}")" && pwd)"
    cd "${script_dir}/../.." && pwd
}

export ROCOBRICK_ROOT="${ROCOBRICK_ROOT:-$(_rocobrick_dds_env_root)}"

export ROS_DISTRO="${ROS_DISTRO:-humble}"
export RMW_IMPLEMENTATION="${RMW_IMPLEMENTATION:-rmw_fastrtps_cpp}"
export ROS_DOMAIN_ID="${ROS_DOMAIN_ID:-0}"
export ROS_LOCALHOST_ONLY="${ROS_LOCALHOST_ONLY:-0}"

# Isaac Sim pip install: bridge extension with bundled ROS 2 Humble runtime
# (rclpy + Fast DDS 2.6.10) and the venv Python that loads it.
export ISAAC_BRIDGE_DIR="${ISAAC_BRIDGE_DIR:-$(ls -d "${ROCOBRICK_ROOT}"/.venv/lib/python3.11/site-packages/isaacsim/exts/isaacsim.ros2.bridge 2>/dev/null | head -1)}"
export ISAAC_PYTHON="${ISAAC_PYTHON:-${ROCOBRICK_ROOT}/.venv/bin/python}"

if [[ -n "${ISAAC_BRIDGE_DIR}" && -d "${ISAAC_BRIDGE_DIR}/${ROS_DISTRO}/lib" ]]; then
    case ":${LD_LIBRARY_PATH:-}:" in
        *":${ISAAC_BRIDGE_DIR}/${ROS_DISTRO}/lib:"*) ;;
        *) export LD_LIBRARY_PATH="${ISAAC_BRIDGE_DIR}/${ROS_DISTRO}/lib${LD_LIBRARY_PATH:+:${LD_LIBRARY_PATH}}" ;;
    esac
    case ":${PYTHONPATH:-}:" in
        *":${ISAAC_BRIDGE_DIR}/${ROS_DISTRO}/rclpy:"*) ;;
        *) export PYTHONPATH="${ISAAC_BRIDGE_DIR}/${ROS_DISTRO}/rclpy${PYTHONPATH:+:${PYTHONPATH}}" ;;
    esac
else
    echo "isaac_host_env: warning: Isaac bridge runtime not found under ${ROCOBRICK_ROOT}/.venv" >&2
fi

# Prefer the generated host profile; regenerate on demand if missing.
export DDS_PROFILE_DIR="${DDS_PROFILE_DIR:-${ROCOBRICK_ROOT}/config/dds/generated}"
export FASTRTPS_DEFAULT_PROFILES_FILE="${FASTRTPS_DEFAULT_PROFILES_FILE:-${DDS_PROFILE_DIR}/host-fastdds-profile.xml}"
if [[ ! -f "${FASTRTPS_DEFAULT_PROFILES_FILE}" ]]; then
    echo "isaac_host_env: ${FASTRTPS_DEFAULT_PROFILES_FILE} missing; generating profiles..." >&2
    python3 "${ROCOBRICK_ROOT}/tools/dds/generate_dds_profiles.py" --domain-id "${ROS_DOMAIN_ID}" >&2
fi

isaac_dds_python() {
    "${ISAAC_PYTHON}" "$@"
}

isaac_dds_env_check() {
    local status="ok"
    [[ -x "${ISAAC_PYTHON}" ]] || status="missing_isaac_python"
    [[ -d "${ISAAC_BRIDGE_DIR}/${ROS_DISTRO}/lib" ]] || status="missing_bridge_libs"
    [[ -f "${FASTRTPS_DEFAULT_PROFILES_FILE}" ]] || status="missing_host_profile"
    python3 - "$status" <<'PY'
import json, os, sys
print(json.dumps({
    "ros_distro": os.environ.get("ROS_DISTRO"),
    "rmw_implementation": os.environ.get("RMW_IMPLEMENTATION"),
    "ros_domain_id": os.environ.get("ROS_DOMAIN_ID"),
    "ros_localhost_only": os.environ.get("ROS_LOCALHOST_ONLY"),
    "isaac_python": os.environ.get("ISAAC_PYTHON"),
    "isaac_bridge_dir": os.environ.get("ISAAC_BRIDGE_DIR"),
    "fastrtps_default_profiles_file": os.environ.get("FASTRTPS_DEFAULT_PROFILES_FILE"),
    "status": sys.argv[1],
}, sort_keys=True))
PY
}

export ROCOBRICK_DDS_ENV_LOADED=1
