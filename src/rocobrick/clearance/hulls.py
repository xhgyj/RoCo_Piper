"""Sim-arbiter clearance checks for the dual-Piper wrist cluster.

MoveIt checks the concave collision meshes; the Isaac host bridge collides the
**convex hulls** of the very same meshes (``approximation=convexHull`` on the
pinned vendor USD, all real contacts kept).  The hull bridges every concavity
of the wrist parts -- up to 25 mm on the gripper base and the wrist-camera
stand, 12 mm on the fingers -- which is why a plan MoveIt reported as
collision-free can jam two wrists together in simulation.

This module measures clearance in the arbiter geometry.  The hulls are the
embedded artifact ``piper_l_sim_hulls.json`` (generated by
``tools/sim_collision_hulls.py`` from the runtime URDF meshes, pinned to the
vendor USD), evaluated with a numpy GJK distance query.  No USD, Pinocchio, or
simulator is required, so the ROS/MoveIt container can gate a plan between
planning and dispatch.
"""

from __future__ import annotations

import json
import math
from dataclasses import dataclass
from pathlib import Path

import numpy as np

ARTIFACT = Path(__file__).with_name("piper_l_sim_hulls.json")
DEFAULT_FLOOR_M = 0.015
_AABB_PREFILTER_M = 0.05
_GJK_TOLERANCE = 1e-12
_GJK_MAX_ITERATIONS = 64


@dataclass(frozen=True)
class Hull:
    """A convex body in its own frame.

    ``planes`` rows are ``[nx, ny, nz, d]`` with the inside convention
    ``nx*x + ny*y + nz*z + d >= 0`` for every point of the hull.
    """

    name: str
    vertices: np.ndarray
    planes: np.ndarray

    def support_local(self, direction: np.ndarray) -> np.ndarray:
        """Return the extreme vertex along a direction given in this frame.

        Returns:
            The vertex with the largest projection on ``direction``.
        """
        index = int(np.argmax(self.vertices @ direction))
        return self.vertices[index]


@dataclass(frozen=True)
class AttachedBody:
    """A local-frame hull rigidly attached to a model link."""

    name: str
    link: str
    local: np.ndarray
    hull: Hull


@dataclass(frozen=True)
class Clearance:
    """One measured minimum between two bodies at a sampled configuration."""

    distance_m: float
    intersecting: bool
    body_a: str
    body_b: str
    sample: int

    @property
    def evidence(self) -> dict[str, object]:
        """Return the JSON-safe record."""
        return {
            "distance_m": self.distance_m,
            "intersecting": self.intersecting,
            "body_a": self.body_a,
            "body_b": self.body_b,
            "sample": self.sample,
        }


@dataclass(frozen=True)
class ClearanceReport:
    """Aggregate verdict for one commanded motion or one pose region."""

    passed: bool
    floor_m: float
    worst: Clearance | None
    samples: int
    covered: dict[str, int] | None = None
    excluded: tuple[str, ...] = ()

    @property
    def evidence(self) -> dict[str, object]:
        """Return the JSON-safe record."""
        return {
            "passed": self.passed,
            "floor_m": self.floor_m,
            "samples": self.samples,
            "worst": self.worst.evidence if self.worst is not None else None,
            "arbiter": "isaac-convex-hull-proxy/v1",
            "covered_bodies": dict(self.covered or {}),
            "excluded_bodies": list(self.excluded),
        }

    def fail_message(self) -> str:
        """Return the operator-facing failure reason."""
        if self.worst is None:
            return "clearance region had no measurable pairs"
        worst = self.worst
        kind = "interpenetration" if worst.intersecting else "clearance"
        return (
            f"{kind} {worst.distance_m * 1000:.2f} mm between "
            f"{worst.body_a} and {worst.body_b} at sample {worst.sample} of "
            f"{self.samples} (sim-arbiter floor {self.floor_m * 1000:.1f} mm)"
        )


def box_hull(name: str, minimum: np.ndarray, maximum: np.ndarray) -> Hull:
    """Return the exact hull of an axis-aligned box in its own frame."""
    corners = np.array(
        [
            [x, y, z]
            for x in (minimum[0], maximum[0])
            for y in (minimum[1], maximum[1])
            for z in (minimum[2], maximum[2])
        ],
        dtype=np.float64,
    )
    planes = []
    for axis in range(3):
        above = np.zeros(3)
        above[axis] = 1.0
        planes.append([*above, -minimum[axis]])
        below = np.zeros(3)
        below[axis] = -1.0
        planes.append([*below, maximum[axis]])
    return Hull(name, corners, np.array(planes, dtype=np.float64))


class SimCollisionHulls:
    """The embedded sim-arbiter hulls, keyed by link name without robot prefix."""

    def __init__(
        self,
        document: dict[str, object] | None = None,
        *,
        include_disabled: bool = False,
    ) -> None:
        """Load the embedded hulls, or an explicit document in tests.

        Bodies the scene bootstrap disables (the wrist camera) are excluded by
        default so the proxy always matches what the simulator collides; pass
        ``include_disabled=True`` to reconstruct the geometry those colliders
        used to contribute.
        """
        if document is None:
            with ARTIFACT.open() as handle:
                document = json.load(handle)
        self.document = document
        links = document["links"]
        assert isinstance(links, dict)
        scale = float(document["quantization_m"])
        self._hulls: dict[str, Hull] = {}
        self._disabled: dict[str, Hull] = {}
        self._excluded: list[str] = []
        for name, entry in links.items():
            assert isinstance(entry, dict)
            hull = Hull(
                name,
                np.array(entry["vertices"], dtype=np.float64) * scale,
                np.array(entry["planes"], dtype=np.float64),
            )
            if entry.get("collision") == "disabled-by-scene":
                self._disabled[name] = hull
                self._excluded.append(name)
                if include_disabled:
                    self._hulls[name] = hull
                continue
            self._hulls[name] = hull

    @property
    def link_names(self) -> tuple[str, ...]:
        """Return every enabled proxied body name."""
        return tuple(sorted(self._hulls))

    @property
    def disabled_names(self) -> tuple[str, ...]:
        """Return the body names the scene bootstrap disables."""
        return tuple(sorted(self._excluded))

    def hull(self, name: str) -> Hull:
        """Return the hull for one body name."""
        return self._hulls[name]


_HULLS: SimCollisionHulls | None = None


def load_hulls() -> SimCollisionHulls:
    """Return the process-wide arbiter hulls (loaded once).

    Returns:
        The embedded sim-arbiter hull set.
    """
    global _HULLS
    if _HULLS is None:
        _HULLS = SimCollisionHulls()
    return _HULLS


# Deterministic tie-break for the support query.  Axis-aligned contacts make
# several vertices exactly extreme; without a generic secondary direction the
# distance loop can stall on a repeated support point while the origin is in
# fact enclosed (measured: two overlapping unit boxes reported +30 mm).  The
# perturbation only orders exactly-tied vertices, so the returned vertex is
# still a true extreme point.
_TIE_BREAK = np.array([1.0, 1.6180339887, 2.7182818285]) * 1e-9


def _support(
    hull: Hull, rotation: np.ndarray, translation: np.ndarray, direction: np.ndarray
) -> np.ndarray:
    local = rotation.T @ direction
    local = local + _TIE_BREAK
    return translation + rotation @ hull.support_local(local)


def _closest_on_simplex(points: np.ndarray) -> tuple[np.ndarray, list[int]]:
    """Closest point to the origin on the convex hull of at most four points.

    Brute force over subsets: project the origin onto each sub-simplex affine
    hull and keep the candidate whose barycentric coordinates are all
    non-negative and sum to at most one (an interior face point).

    Returns:
        The closest point and the simplex indices that support it.
    """
    best_distance = math.inf
    best_point = np.zeros(3)
    best_subset: list[int] = []
    count = len(points)
    for mask in range(1, 1 << count):
        subset = [index for index in range(count) if mask & (1 << index)]
        base = points[subset[0]]
        if len(subset) == 1:
            point = base
        else:
            columns = np.array([points[index] - base for index in subset[1:]]).T
            gram = columns.T @ columns
            if abs(float(np.linalg.det(gram))) <= 1e-18:
                continue
            weights = np.linalg.solve(gram, -columns.T @ base)
            if np.any(weights < -1e-9) or float(weights.sum()) > 1.0 + 1e-9:
                continue
            point = base + columns @ weights
        distance = float(point @ point)
        if distance < best_distance - 1e-18:
            best_distance = distance
            best_point = point
            best_subset = subset
    return best_point, best_subset


def gjk_distance(
    hull_a: Hull,
    rotation_a: np.ndarray,
    translation_a: np.ndarray,
    hull_b: Hull,
    rotation_b: np.ndarray,
    translation_b: np.ndarray,
) -> tuple[float, bool]:
    """Return (distance, intersecting) between two posed convex hulls.

    Standard GJK closest-point query on the Minkowski difference: iterate
    toward the origin and stop when the support point stops making progress.

    Returns:
        Distance in metres (0.0 with ``intersecting`` True when they overlap).
    """
    direction = translation_a - translation_b
    if float(direction @ direction) < 1e-18:
        direction = np.array([1.0, 0.0, 0.0])
    closest = _support(hull_a, rotation_a, translation_a, -direction) - _support(
        hull_b, rotation_b, translation_b, direction
    )
    simplex: list[np.ndarray] = []
    for _ in range(_GJK_MAX_ITERATIONS):
        distance_squared = float(closest @ closest)
        if distance_squared <= 1e-20:
            return 0.0, True
        candidate = _support(
            hull_a, rotation_a, translation_a, -closest
        ) - _support(hull_b, rotation_b, translation_b, closest)
        if (
            distance_squared - float(closest @ candidate)
            <= _GJK_TOLERANCE * max(1.0, distance_squared)
        ):
            return math.sqrt(distance_squared), False
        if any(
            float(np.linalg.norm(candidate - existing)) <= 1e-13
            for existing in simplex
        ):
            return math.sqrt(distance_squared), False
        # Note: the closest distance may temporarily grow before the simplex
        # spans the true closest feature; only the support-plane convergence
        # test and the duplicate test terminate the loop.
        simplex.append(candidate)
        closest, subset = _closest_on_simplex(np.array(simplex))
        simplex = [simplex[index] for index in subset]
    return math.sqrt(max(float(closest @ closest), 0.0)), False


def _penetration_depth(
    hull_a: Hull,
    rotation_a: np.ndarray,
    translation_a: np.ndarray,
    hull_b: Hull,
    rotation_b: np.ndarray,
    translation_b: np.ndarray,
) -> float:
    """Lower-bound the intersection depth of A inside B by vertex plane depths.

    Returns:
        The deepest penetration of any A vertex inside B, or 0.0.
    """
    planes = hull_b.planes
    normals = planes[:, :3] @ rotation_b.T
    offsets = planes[:, 3] - normals @ translation_b
    world = hull_a.vertices @ rotation_a.T + translation_a
    depths = (world @ normals.T + offsets).min(axis=1)
    inside = depths > 0.0
    if not inside.any():
        return 0.0
    return float(depths[inside].max())


def pair_distance(
    hull_a: Hull, pose_a: np.ndarray, hull_b: Hull, pose_b: np.ndarray
) -> tuple[float, bool]:
    """Return (distance, intersecting) for two hulls at world poses."""
    return gjk_distance(
        hull_a, pose_a[:3, :3], pose_a[:3, 3], hull_b, pose_b[:3, :3], pose_b[:3, 3]
    )


def _aabb(pose: np.ndarray, hull: Hull) -> tuple[np.ndarray, np.ndarray]:
    world = hull.vertices @ pose[:3, :3].T + pose[:3, 3]
    return world.min(axis=0), world.max(axis=0)


def _aabb_gap(
    low_a: np.ndarray, high_a: np.ndarray, low_b: np.ndarray, high_b: np.ndarray
) -> float:
    gap = np.maximum(np.maximum(low_b - high_a, low_a - high_b), 0.0)
    return float(np.linalg.norm(gap))


def _owner(link: str) -> str | None:
    """Return the robot id a ``piper_0_link1`` style link belongs to."""
    parts = link.split("_")
    if len(parts) >= 3 and parts[0] == "piper":
        return f"{parts[0]}_{parts[1]}"
    return None


@dataclass(frozen=True)
class _Body:
    name: str
    robot: str
    pose: np.ndarray
    hull: Hull
    low: np.ndarray
    high: np.ndarray


def region_clearance(
    poses: dict[str, dict[str, np.ndarray]],
    *,
    hulls: SimCollisionHulls | None = None,
    attached: dict[str, list[AttachedBody]] | None = None,
    floor_m: float = DEFAULT_FLOOR_M,
    sample: int = 0,
) -> ClearanceReport:
    """Measure the cross-robot minimum over one posed configuration.

    ``poses`` maps robot id to model link name to world transform.  Bodies come
    from the arbiter proxy by link name suffix (``piper_0_gripper_base`` ->
    ``gripper_base``); ``attached`` adds local-frame hulls rigidly attached to a
    named link of a robot's pose map (for example a held brick on
    ``piper_0_rocobrick_tcp``).

    A configuration in which every pair stays beyond the prefilter passes:
    the reported minimum is then simply the prefilter distance or more.

    Returns:
        The verdict for this configuration.
    """
    proxy = hulls if hulls is not None else load_hulls()
    bodies: dict[str, list[_Body]] = {}
    for robot, links in poses.items():
        collected: list[_Body] = []
        for link, pose in links.items():
            owner = _owner(link)
            if owner is not None and owner != robot:
                # A foreign robot's link never forms a cross-robot pair.
                continue
            suffix = link[len(robot) + 1 :] if link.startswith(f"{robot}_") else link
            if suffix not in proxy.link_names:
                continue
            hull = proxy.hull(suffix)
            low, high = _aabb(pose, hull)
            collected.append(_Body(link, robot, pose, hull, low, high))
        for attachment in (attached or {}).get(robot, []):
            base = links.get(attachment.link)
            if base is None:
                continue
            pose = base @ attachment.local
            low, high = _aabb(pose, attachment.hull)
            collected.append(
                _Body(attachment.name, robot, pose, attachment.hull, low, high)
            )
        bodies[robot] = collected
    robots = sorted(bodies)
    worst: Clearance | None = None
    for left_index, left in enumerate(robots):
        for right in robots[left_index + 1 :]:
            for body_a in bodies[left]:
                for body_b in bodies[right]:
                    if (
                        _aabb_gap(body_a.low, body_a.high, body_b.low, body_b.high)
                        > _AABB_PREFILTER_M
                    ):
                        continue
                    distance, intersecting = pair_distance(
                        body_a.hull, body_a.pose, body_b.hull, body_b.pose
                    )
                    if intersecting:
                        depth = max(
                            _penetration_depth(
                                body_a.hull,
                                body_a.pose[:3, :3],
                                body_a.pose[:3, 3],
                                body_b.hull,
                                body_b.pose[:3, :3],
                                body_b.pose[:3, 3],
                            ),
                            _penetration_depth(
                                body_b.hull,
                                body_b.pose[:3, :3],
                                body_b.pose[:3, 3],
                                body_a.hull,
                                body_a.pose[:3, :3],
                                body_a.pose[:3, 3],
                            ),
                        )
                        distance = -depth
                    if worst is None or distance < worst.distance_m:
                        worst = Clearance(
                            distance_m=distance,
                            intersecting=intersecting,
                            body_a=body_a.name,
                            body_b=body_b.name,
                            sample=sample,
                        )
    covered = {robot: len(bodies[robot]) for robot in robots}
    excluded = proxy.disabled_names
    if worst is None:
        # Every pair is farther apart than the prefilter distance.
        return ClearanceReport(
            passed=True,
            floor_m=floor_m,
            worst=None,
            samples=1,
            covered=covered,
            excluded=excluded,
        )
    return ClearanceReport(
        passed=worst.distance_m >= floor_m,
        floor_m=floor_m,
        worst=worst,
        samples=1,
        covered=covered,
        excluded=excluded,
    )
